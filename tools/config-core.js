/* Shared offline configuration compiler; no network or host-app access. */
(function (root) {
  'use strict';
  const regionNames = {
    home: '首页背景', account: '账号与余额', general: '通用设置', models: '模型',
    plugins: '内置插件', presets: 'Agent 预设', archive: '已归档会话', web: 'Web 插件',
    skins: '皮肤', pets: '宠物设置插画', workshop: '创意工坊', usage: '使用统计',
    'settings-sidebar': '设置左栏', 'main-sidebar': '主侧栏'
  };
  const defaults = {
    schemaVersion: 1, composerWidth: 760, fontSize: 16, motto: '让灵感，慢慢发芽',
    font: 'wenkai', decorations: true,
    light: { ink: '#704b6d', muted: '#80667d', accent: '#935b88', paper: '#fffaf4', soft: '#f7eaf2', line: '#e1c9d7', wood: '#e8c8a9' },
    dark: { ink: '#f1ddea', muted: '#d0b6c8', accent: '#ddb2cf', paper: '#302733', soft: '#483447', line: '#70556b', wood: '#6c5148' },
    images: {}
  };
  function contrast(a, b) {
    const lum = h => h.slice(1).match(/../g).map(v => parseInt(v, 16) / 255).map(v => v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4).reduce((s, v, i) => s + v * [.2126, .7152, .0722][i], 0);
    return (Math.max(lum(a), lum(b)) + .05) / (Math.min(lum(a), lum(b)) + .05);
  }
  function normalize(value = {}) {
    if (!value || typeof value !== 'object' || Array.isArray(value)) throw Error('配置必须是 JSON 对象');
    for (const key of Object.keys(value)) if (!Object.hasOwn(defaults, key)) throw Error('未知配置字段：' + key);
    const c = JSON.parse(JSON.stringify(defaults));
    for (const key of ['schemaVersion', 'composerWidth', 'fontSize', 'motto', 'font', 'decorations']) if (Object.hasOwn(value, key)) c[key] = value[key];
    if (c.schemaVersion !== 1) throw Error('不支持的配置版本');
    if (!Number.isInteger(c.composerWidth) || c.composerWidth < 560 || c.composerWidth > 1100) throw Error('输入框宽度需为 560–1100 的整数');
    if (!Number.isInteger(c.fontSize) || c.fontSize < 14 || c.fontSize > 20) throw Error('字号需为 14–20 的整数');
    if (typeof c.motto !== 'string' || [...c.motto].length > 24 || /[\x00-\x1f\x7f]/.test(c.motto)) throw Error('题字最多 24 字，不能含控制字符');
    if (!['wenkai', 'system'].includes(c.font) || typeof c.decorations !== 'boolean') throw Error('字体或装饰选项无效');
    for (const theme of ['light', 'dark']) {
      if (Object.hasOwn(value, theme)) {
        if (!value[theme] || typeof value[theme] !== 'object' || Array.isArray(value[theme])) throw Error('配色无效');
        for (const [key, hex] of Object.entries(value[theme])) {
          if (!Object.hasOwn(c[theme], key) || typeof hex !== 'string' || !/^#[\da-f]{6}$/i.test(hex)) throw Error('颜色必须是 #RRGGBB：' + key);
          c[theme][key] = hex.toLowerCase();
        }
      }
      for (const key of ['ink', 'muted', 'accent']) if (contrast(c[theme][key], c[theme].paper) < 4.5) throw Error(theme + ' 的 ' + key + ' 与底色对比度低于 4.5，请调深文字或调浅底色');
    }
    if (Object.hasOwn(value, 'images')) {
      if (!value.images || typeof value.images !== 'object' || Array.isArray(value.images)) throw Error('图片配置无效');
      let bytes = 0;
      for (const [id, image] of Object.entries(value.images)) {
        if (!Object.hasOwn(regionNames, id)) throw Error('未知图片区域：' + id);
        if (image !== null && image !== false) {
          if (typeof image !== 'string' || !/^data:image\/(?:png|jpeg|webp);base64,[A-Za-z0-9+/]+={0,2}$/.test(image)) throw Error('仅支持 PNG、JPEG、WebP 本地图片');
          const encoded = image.split(',')[1];
          if (encoded.length % 4 !== 0 || image.length > 12 * 1024 * 1024) throw Error('图片编码无效或超过 8 MB');
          const head = typeof atob === 'function' ? atob(encoded.slice(0, 32)) : '';
          const kind = image.slice(11, image.indexOf(';'));
          if ((kind === 'png' && !head.startsWith('\x89PNG\r\n\x1a\n')) ||
              (kind === 'jpeg' && !head.startsWith('\xff\xd8\xff')) ||
              (kind === 'webp' && !(head.startsWith('RIFF') && head.slice(8, 12) === 'WEBP'))) throw Error('图片内容与格式不匹配');
          bytes += image.length;
        }
        c.images[id] = image;
      }
      if (bytes > 60 * 1024 * 1024) throw Error('图片总量过大，请压缩后重试');
    }
    return c;
  }
  const cssString = value => '"' + [...value].map(ch => '\\' + ch.codePointAt(0).toString(16) + ' ').join('') + '"';
  const scope = 'html body:is([data-ds-dark-theme],:not([data-ds-dark-theme]))';
  function imageSelector(id) {
    if (id === 'home') return '[data-conversation-region="chat"]::before';
    if (id === 'main-sidebar') return '._2H3hWW_root:not(._2H3hWW_collapsed) ._2H3hWW_footArea::before';
    if (id === 'settings-sidebar') return '[data-shortcut-modal="settings"].wCInkW_panel > nav::after';
    const index = Object.keys(regionNames).indexOf(id);
    return '[data-shortcut-modal="settings"].wCInkW_panel:has(> nav .wCInkW_navCell:nth-child(' + index + ')[aria-current="true"]) .wCInkW_options::after';
  }
  function compile(value) {
    const c = normalize(value), css = ['/* Generated by Whale Desk offline configuration tool. */'];
    for (const mode of ['light', 'dark']) {
      const target = mode === 'light' ? 'html body:not([data-ds-dark-theme])' : 'html body[data-ds-dark-theme]';
      const palette = c[mode];
      const fg = contrast('#ffffff', palette.accent) >= contrast('#242024', palette.accent) ? '#ffffff' : '#242024';
      css.push(target + '{' + Object.entries(palette).map(([k, v]) => '--desk-' + k + ':' + v + '!important;').join('') + '--dsw-alias-brand-primary-invert:' + fg + '!important;--dsw-alias-label-primary-foreground:' + fg + '!important;--dsw-alias-label-primary-inverted:' + fg + '!important;}');
    }
    css.push(scope + ' [data-conversation-region="chat"] [class*="composerStack"]{width:min(' + c.composerWidth + 'px,calc(100% - 24px))!important;max-width:' + c.composerWidth + 'px!important;}');
    css.push(scope + ' [data-conversation-region="chat"] [data-composer-card][data-composer-card]{max-width:' + c.composerWidth + 'px!important;}');
    css.push(scope + ' [data-composer-card] :is(textarea,[contenteditable="true"]){font-size:' + c.fontSize + 'px!important;}');
    css.push(scope + ' .Dc7zOa_headerBlank::after{content:' + cssString(c.motto) + '!important;max-width:calc(100% - 250px)!important;overflow:hidden!important;white-space:nowrap!important;text-overflow:ellipsis!important;}');
    if (c.font === 'system') css.push(scope + ' :is(._2H3hWW_root,[data-shortcut-modal="settings"],[data-composer-card],button,input,textarea,select,[role="menu"]){font-family:"Microsoft YaHei","Segoe UI",sans-serif!important;}');
    if (!c.decorations) css.push(scope + ' .Dc7zOa_headerBlank::before,' + scope + ' [data-conversation-region="chat"] [data-composer-card][data-composer-card]::before{display:none!important;}');
    for (const [id, data] of Object.entries(c.images)) {
      if (data === null) continue;
      const target = scope + ' ' + imageSelector(id);
      const targets = id === 'home' ? target + ',' + scope + ' [data-conversation-region="chat"]:has(> .Dc7zOa_headerBlank)::before' : target;
      css.push(targets + '{' + (data === false ? 'display:none!important;' : 'display:block!important;background-image:url("' + data + '")!important;') + '}');
      if (id === 'home' && data !== false) css.push('html body[data-ds-dark-theme][data-ds-dark-theme] [data-conversation-region="chat"]::before,html body[data-ds-dark-theme][data-ds-dark-theme] [data-conversation-region="chat"]:has(> .Dc7zOa_headerBlank)::before{background-image:linear-gradient(#241a2caa,#241a2cd9),url("' + data + '")!important;}');
    }
    return css.join('\n') + '\n';
  }
  root.WhaleDeskConfig = { defaults, regionNames, normalize, compile, contrast };
})(globalThis);
